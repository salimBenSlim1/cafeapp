const serverRoute=require('express').Router()
const serverController=require('../contoller/servers')
const { generateServerReport } = require('../contoller/users')
const validate = require('../middleware/validate')
const validateParams = require('../middleware/validateParams')
const { paramSchema } = require('../validators/param.validator')
const { serverSchema } = require('../validators/server.validators')
serverRoute.post('/add-server',validate(serverSchema), serverController.addServer)
serverRoute.put('/assign-tables/:id',validateParams(paramSchema), serverController.assignTableToServer)
serverRoute.put('/update-server/:id',validateParams(paramSchema),serverController.updateServerOfCoffe)
serverRoute.put('/clear-tables/:id',validateParams(paramSchema),serverController.clearTablesServerOfCoffe)
serverRoute.get('/get-servers',serverController.getServersOfCoffe)
serverRoute.get('/waiter-report/:serverId',generateServerReport)
serverRoute.get('/get-server-table/:id',serverController.getServerTables)
serverRoute.delete('/delete-servers/:id',serverController.deleteServerOfCoffe)

module.exports=serverRoute